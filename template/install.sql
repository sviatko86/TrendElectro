create or replace function public.claim_birthday_gift(p_name text, p_contact text, p_birthday date, p_consent boolean)
 returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare s jsonb; pct numeric; c text; dg text; st date; sub record; v_code text; v_until timestamptz;
begin
  select value into s from public.settings where key = 'shop';
  if coalesce((s->>'bday_on')::boolean, false) is not true then return jsonb_build_object('ok', false, 'state', 'off'); end if;
  pct := least(coalesce(nullif(s->>'bday_percent','')::numeric, 0), 90);
  if pct <= 0 then return jsonb_build_object('ok', false, 'state', 'off'); end if;
  if p_consent is not true then raise exception 'Потрібна згода на обробку даних'; end if;
  if p_birthday is null or p_birthday > current_date or p_birthday < date '1900-01-01' then raise exception 'Невірна дата'; end if;
  c := lower(trim(coalesce(p_contact, '')));
  if position('@' in c) > 0 then
    if c !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(c) > 120 then raise exception 'Невірний email'; end if;
  else
    dg := regexp_replace(c, '\D', '', 'g');
    if length(dg) = 10 and left(dg,1) = '0' then dg := '38' || dg; end if;
    if length(dg) = 9 then dg := '380' || dg; end if;
    if length(dg) < 11 or length(dg) > 13 then raise exception 'Невірний телефон або email'; end if;
    c := dg;
  end if;

  st := public.bday_start(p_birthday);
  insert into public.bday_subs(contact, name, birthday) values (c, left(trim(coalesce(p_name,'')), 100), p_birthday)
    on conflict (contact) do update set name = coalesce(nullif(excluded.name,''), public.bday_subs.name), birthday = coalesce(public.bday_subs.birthday, excluded.birthday);
  select * into sub from public.bday_subs where contact = c;
  -- дата, збережена при першій реєстрації, не змінюється
  st := public.bday_start(sub.birthday);
  if st is null then
    return jsonb_build_object('ok', false, 'state', 'later');
  end if;
  v_until := ((st + public.bday_days())::timestamp) at time zone 'Europe/Kyiv';
  if sub.last_year = extract(year from st)::int and sub.last_code is not null then
    return jsonb_build_object('ok', true, 'state', 'again', 'code', sub.last_code, 'percent', pct, 'until', (st + public.bday_days() - 1));
  end if;
  v_code := 'BD' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
  insert into public.promo_codes(code, percent, uses_left, expires_at, active, title)
    values (v_code, pct, 1, v_until, true, 'Подарунок на день народження');
  update public.bday_subs set last_code = v_code, last_year = extract(year from st)::int where id = sub.id;
  return jsonb_build_object('ok', true, 'state', 'new', 'code', v_code, 'percent', pct, 'until', (st + public.bday_days() - 1));
end $function$;

create or replace function public.claim_my_birthday()
 returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare s jsonb; b date; st date; pct numeric;
begin
  if auth.uid() is null then raise exception 'Увійдіть в акаунт'; end if;
  select value into s from public.settings where key = 'shop';
  if coalesce((s->>'bday_on')::boolean, false) is not true then return jsonb_build_object('ok', false, 'state', 'off'); end if;
  pct := least(coalesce(nullif(s->>'bday_percent','')::numeric, 0), 90);
  select birthday into b from public.profiles where id = auth.uid();
  st := public.bday_start(b);
  if pct <= 0 or st is null then return jsonb_build_object('ok', false, 'state', 'not_now'); end if;
  update public.profiles set bday_claim = st where id = auth.uid();
  return jsonb_build_object('ok', true, 'percent', pct, 'start', st, 'until', st + public.bday_days() - 1);
end $function$;


create or replace function public.landing_hit(p_slug text, p_kind text)
 returns void language plpgsql security definer set search_path to 'public' as $function$
declare d date := (now() at time zone 'Europe/Kyiv')::date;
begin
  if not exists (select 1 from public.landings where slug = p_slug and active) then return; end if;
  if p_kind not in ('view', 'click', 'order') then return; end if;
  insert into public.landing_stats(slug, day, views, clicks, orders)
    values (p_slug, d, (p_kind = 'view')::int, (p_kind = 'click')::int, (p_kind = 'order')::int)
  on conflict (slug, day) do update set
    views = public.landing_stats.views + (p_kind = 'view')::int,
    clicks = public.landing_stats.clicks + (p_kind = 'click')::int,
    orders = public.landing_stats.orders + (p_kind = 'order')::int;
end $function$;


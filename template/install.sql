-- Повідомлення про замовлення в Telegram. Токен і чат лежать у таблиці app_secrets (див. README).
-- Адреса адмінки береться з settings.shop.site_url.
create or replace function public.notify_order_telegram()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare tok text; cid text; txt text; it jsonb; site text;
begin
  select value into tok from public.app_secrets where name = 'telegram_bot_token';
  select value into cid from public.app_secrets where name = 'telegram_chat_id';
  if tok is null or cid is null then return new; end if;
  select coalesce(value->>'site_url', '') into site from public.settings where key = 'shop';
  txt := 'Нове замовлення №' || new.id || E'\n' || new.customer_name || ', ' || new.phone
      || E'\n' || coalesce(new.delivery, '') || ', ' || coalesce(new.address, '')
      || E'\nОплата: ' || coalesce(new.payment, '') || coalesce(E'\n' || new.comment, '') || E'\n';
  for it in select * from jsonb_array_elements(new.items) loop
    txt := txt || E'\n' || (it->>'id') || ' · ' || (it->>'name') || ' × ' || (it->>'qty');
  end loop;
  txt := txt || E'\n\nРазом: ' || new.total || ' грн';
  if coalesce(site, '') <> '' then txt := txt || E'\n' || rtrim(site, '/') || '/admin.html'; end if;
  perform net.http_post(
    url := 'https://api.telegram.org/bot' || tok || '/sendMessage',
    headers := '{"Content-Type":"application/json"}'::jsonb,
    body := jsonb_build_object('chat_id', cid, 'text', left(txt, 3900))
  );
  return new;
exception when others then
  return new;   -- проблема з Telegram ніколи не блокує замовлення
end $function$;


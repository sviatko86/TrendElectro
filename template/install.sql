create or replace function public.orders_stock_check()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare v jsonb; it jsonb; s integer; nm text;
begin
  select value into v from public.settings where key = 'shop';
  if not coalesce((v->>'stock_on')::boolean, false) then return new; end if;
  for it in select * from jsonb_array_elements(new.items) loop
    select stock, name into s, nm from public.products where id = it->>'id' for update;
    if s is not null and s < coalesce((it->>'qty')::int, 1) then
      raise exception 'Товару «%» залишилось лише % шт. Зменшіть кількість у кошику.', nm, s;
    end if;
  end loop;
  return new;
end $function$;

create or replace function public.orders_stock_take()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare v jsonb; it jsonb;
begin
  select value into v from public.settings where key = 'shop';
  if not coalesce((v->>'stock_on')::boolean, false) then return new; end if;
  for it in select * from jsonb_array_elements(new.items) loop
    update public.products
       set stock = greatest(stock - coalesce((it->>'qty')::int, 1), 0),
           in_stock = (greatest(stock - coalesce((it->>'qty')::int, 1), 0) > 0)
     where id = it->>'id' and stock is not null;
  end loop;
  return new;
end $function$;

create or replace function public.orders_stock_back()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare v jsonb; it jsonb;
begin
  if not (new.status = 'cancelled' and old.status is distinct from 'cancelled') then return new; end if;
  select value into v from public.settings where key = 'shop';
  if not coalesce((v->>'stock_on')::boolean, false) then return new; end if;
  for it in select * from jsonb_array_elements(new.items) loop
    update public.products
       set stock = stock + coalesce((it->>'qty')::int, 1), in_stock = true
     where id = it->>'id' and stock is not null;
  end loop;
  return new;
end $function$;

create or replace function public.use_promo()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
begin
  if new.promo_code is not null then
    update public.promo_codes set uses_left = uses_left - 1
    where code = upper(new.promo_code) and uses_left is not null and uses_left > 0;
  end if;
  return new;
end $function$;


create or replace function public.is_admin()
 returns boolean language sql stable security definer set search_path to 'public' as $function$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false)
$function$;

create or replace function public.loy_cfg()
 returns jsonb language sql stable security definer set search_path to 'public' as $function$
  select coalesce((select value from public.settings where key = 'loyalty'),
    '{"on":true,"one":true,"tiers":[{"k":"silver","p":5,"f":0},{"k":"gold","p":10,"f":5000},{"k":"platinum","p":15,"f":15000},{"k":"vip","p":20,"f":50000}]}'::jsonb)
$function$;

create or replace function public.loy_recalc(p_uid uuid)
 returns void language plpgsql security definer set search_path to 'public' as $function$
declare sp numeric; t jsonb; k text := 'silver'; pc numeric := 5; g text;
begin
  if p_uid is null then return; end if;
  select coalesce(sum(total), 0) into sp from public.orders where user_id = p_uid and status = 'done';
  select sp + coalesce(loyalty_adj, 0), card_gift into sp, g from public.profiles where id = p_uid;
  if sp is null then return; end if;
  for t in select * from jsonb_array_elements(public.loy_cfg()->'tiers') where value->>'k' <> 'vip' order by (value->>'f')::numeric loop
    if (t->>'f')::numeric <= sp then k := t->>'k'; pc := (t->>'p')::numeric; end if;
  end loop;
  if g is not null then
    for t in select * from jsonb_array_elements(public.loy_cfg()->'tiers') where value->>'k' = g loop
      if (t->>'p')::numeric > pc then k := t->>'k'; pc := (t->>'p')::numeric; end if;
    end loop;
  end if;
  update public.profiles set loyalty_spent = sp, card_tier = k, card_pct = pc where id = p_uid;
end $function$;

create or replace function public.loy_trg()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
begin
  if tg_op = 'DELETE' then perform public.loy_recalc(old.user_id); return old; end if;
  perform public.loy_recalc(new.user_id);
  if tg_op = 'UPDATE' and old.user_id is distinct from new.user_id then perform public.loy_recalc(old.user_id); end if;
  return new;
end $function$;

create or replace function public.admin_loy_recalc_all()
 returns integer language plpgsql security definer set search_path to 'public' as $function$
declare r record; n int := 0;
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  for r in select id from public.profiles loop perform public.loy_recalc(r.id); n := n + 1; end loop;
  return n;
end $function$;


create or replace function public.log_order_change()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
begin
  if tg_op = 'INSERT' then
    insert into public.order_events (order_id, kind, text) values (new.id, 'created', new.status);
    return new;
  end if;
  if new.status is distinct from old.status then
    insert into public.order_events (order_id, kind, text) values (new.id, 'status', new.status);
  end if;
  if new.ttn is distinct from old.ttn then
    insert into public.order_events (order_id, kind, text) values (new.id, 'ttn', coalesce(new.ttn, ''));
  end if;
  if new.manager_note is distinct from old.manager_note then
    insert into public.order_events (order_id, kind, text) values (new.id, 'note', coalesce(new.manager_note, ''));
  end if;
  new.updated_at := now();
  return new;
end $function$;

create or replace function public.log_product_change()
 returns trigger language plpgsql security definer set search_path to 'public' as $function$
begin
  if tg_op = 'UPDATE' then
    if (to_jsonb(old) - 'updated_at') = (to_jsonb(new) - 'updated_at') then return new; end if;
    insert into public.product_history (product_id, action, old) values (old.id, 'update', to_jsonb(old));
    return new;
  end if;
  insert into public.product_history (product_id, action, old) values (old.id, 'delete', to_jsonb(old));
  return old;
end $function$;


create or replace function public.create_order(p_name text, p_phone text, p_delivery text, p_address text, p_payment text, p_comment text, p_promo text, p_items jsonb)
 returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare
  st jsonb; gm numeric; gd numeric; bc jsonb;
  it jsonb; pr record; v_qty int; v_m numeric; v_d numeric; v_unit numeric;
  k1 text; k2 text; k3 text;
  v_sum numeric := 0; v_lines jsonb := '[]'::jsonb;
  v_pdisc numeric := 0; v_cdisc numeric; v_disc numeric; v_total numeric;
  v_code text := null; v_oid bigint; v_card numeric := 0; v_one numeric := 0;
begin
  if coalesce(trim(p_name), '') = '' or coalesce(trim(p_phone), '') = '' then
    raise exception 'Вкажіть імʼя та телефон';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0
     or jsonb_array_length(p_items) > 100 then
    raise exception 'Кошик порожній';
  end if;

  select value into st from public.settings where key = 'pricing';
  gm := coalesce((st->>'markup_percent')::numeric, 0);
  gd := coalesce((st->>'discount_percent')::numeric, 0);
  bc := coalesce(st->'by_category', '{}'::jsonb);

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 999 then raise exception 'Невірна кількість'; end if;
    select * into pr from public.products where id = it->>'id' and active and in_stock;
    if not found then raise exception 'Товар недоступний: %', it->>'id'; end if;

    k1 := pr.category;
    k2 := case when pr.subcategory is not null then k1 || ' › ' || pr.subcategory end;
    k3 := case when k2 is not null and pr.subcategory2 is not null then k2 || ' › ' || pr.subcategory2 end;
    v_m := coalesce((bc->k3->>'m')::numeric, (bc->k2->>'m')::numeric, (bc->k1->>'m')::numeric, gm);
    v_d := coalesce((bc->k3->>'d')::numeric, (bc->k2->>'d')::numeric, (bc->k1->>'d')::numeric, gd);

    v_unit := round(pr.price * (1 + v_m / 100) * (1 - v_d / 100), 2);
    v_sum := v_sum + v_unit * v_qty;
    v_lines := v_lines || jsonb_build_object('id', pr.id, 'name', pr.name, 'qty', v_qty, 'price', v_unit);
  end loop;

  select coalesce(discount_percent, 0), case when coalesce((public.loy_cfg()->>'on')::boolean, true) then coalesce(card_pct, 0) else 0 end
    into v_pdisc, v_card from public.profiles where id = auth.uid();
  v_pdisc := greatest(coalesce(v_pdisc, 0), coalesce(v_card, 0), public.bday_percent(auth.uid()));
  -- разова знижка за велике замовлення (за тими ж порогами, що й картки)
  if coalesce((public.loy_cfg()->>'one')::boolean, true) then
    select coalesce(max((t->>'p')::numeric), 0) into v_one
      from jsonb_array_elements(public.loy_cfg()->'tiers') t
      where (t->>'f')::numeric > 0 and (t->>'f')::numeric <= v_sum;
    v_pdisc := greatest(v_pdisc, v_one);
  end if;

  if coalesce(trim(p_promo), '') <> '' then
    select pc.percent into v_cdisc from public.promo_codes pc
      where pc.code = upper(trim(p_promo)) and pc.active
        and (pc.uses_left is null or pc.uses_left > 0)
        and (pc.expires_at is null or pc.expires_at > now())
        and (pc.client_id is null or pc.client_id = auth.uid());
    if v_cdisc is null then raise exception 'Промокод недійсний або прострочений'; end if;
    if v_cdisc > v_pdisc then v_code := upper(trim(p_promo)); end if;
  end if;

  v_disc := greatest(v_pdisc, coalesce(v_cdisc, 0));
  v_total := round(v_sum * (100 - v_disc) / 100, 2);

  insert into public.orders
    (user_id, customer_name, phone, delivery, address, payment, comment, promo_code, items, total)
  values
    (auth.uid(), left(trim(p_name), 200), left(trim(p_phone), 50), left(p_delivery, 200),
     left(p_address, 500), left(p_payment, 100),
     nullif(concat_ws(' · ', case when v_disc > 0 then 'Знижка ' || trim_scale(round(v_disc, 2))::text || '%' end, left(p_comment, 1000)), ''),
     v_code, v_lines, v_total)
  returning id into v_oid;

  return jsonb_build_object('id', v_oid, 'total', v_total, 'discount', v_disc, 'items', v_lines);
end $function$;


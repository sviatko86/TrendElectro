create or replace function public.move_category(p_old text[], p_new text[])
 returns integer language plpgsql security definer set search_path to 'public' as $function$
declare n int; cnt int;
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  n := array_length(p_old, 1);
  if n is null or p_new is null or array_length(p_new, 1) is null then raise exception 'Невірний шлях'; end if;
  with src as (
    select id, array_remove(array[category, subcategory, subcategory2], null) as pth from public.products
  ), tgt as (
    select id, p_new || pth[n+1:3] as np from src where pth[1:n] = p_old
  )
  update public.products p set category = tgt.np[1], subcategory = tgt.np[2], subcategory2 = tgt.np[3], updated_at = now()
  from tgt where p.id = tgt.id and array_length(tgt.np, 1) <= 3;
  get diagnostics cnt = row_count;

  update public.categories c
     set path = array_to_string(p_new || (string_to_array(c.path, ' › '))[n+1:3], ' › '), updated_at = now()
   where (string_to_array(c.path, ' › '))[1:n] = p_old
     and not exists (select 1 from public.categories c2
                      where c2.path = array_to_string(p_new || (string_to_array(c.path, ' › '))[n+1:3], ' › '));
  return cnt;
end $function$;

create or replace function public.restore_product(p_hist bigint)
 returns text language plpgsql security definer set search_path to 'public' as $function$
declare h public.product_history; r public.products;
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  select * into h from public.product_history where id = p_hist;
  if not found then raise exception 'Запис журналу не знайдено'; end if;
  r := jsonb_populate_record(null::public.products, h.old);
  r.updated_at := now();
  delete from public.products where id = r.id;
  insert into public.products select (r).*;
  return r.id;
end $function$;

create or replace function public.bday_days()
 returns integer language plpgsql stable security definer set search_path to 'public' as $function$
declare s jsonb; n int;
begin
  select value into s from public.settings where key = 'shop';
  begin n := round(coalesce(nullif(s->>'bday_days','')::numeric, 3)); exception when others then n := 3; end;
  return greatest(1, least(14, n));
end $function$;

create or replace function public.bday_active(b date)
 returns boolean language plpgsql stable as $function$
declare t date := (now() at time zone 'Europe/Kyiv')::date; y int; d date;
begin
  if b is null then return false; end if;
  for y in (extract(year from t)::int - 1)..(extract(year from t)::int) loop
    d := case when extract(month from b) = 2 and extract(day from b) = 29
               and (make_date(y,3,1) - make_date(y,2,1)) = 28
              then make_date(y,2,28)
              else make_date(y, extract(month from b)::int, extract(day from b)::int) end;
    if t between d and d + public.bday_days() - 1 then return true; end if;
  end loop;
  return false;
end $function$;

create or replace function public.bday_start(b date)
 returns date language plpgsql stable as $function$
declare t date := (now() at time zone 'Europe/Kyiv')::date; y int; d date;
begin
  if b is null then return null; end if;
  for y in (extract(year from t)::int - 1)..(extract(year from t)::int) loop
    d := case when extract(month from b) = 2 and extract(day from b) = 29
               and (make_date(y,3,1) - make_date(y,2,1)) = 28
              then make_date(y,2,28)
              else make_date(y, extract(month from b)::int, extract(day from b)::int) end;
    if t between d and d + public.bday_days() - 1 then return d; end if;
  end loop;
  return null;
end $function$;

create or replace function public.bday_percent(uid uuid)
 returns numeric language plpgsql stable security definer set search_path to 'public' as $function$
declare s jsonb; b date; c date; st date; pct numeric;
begin
  if uid is null then return 0; end if;
  select value into s from public.settings where key = 'shop';
  if coalesce((s->>'bday_on')::boolean, false) is not true then return 0; end if;
  pct := coalesce(nullif(s->>'bday_percent','')::numeric, 0);
  select birthday, bday_claim into b, c from public.profiles where id = uid;
  st := public.bday_start(b);
  if pct > 0 and st is not null and c = st then return least(pct, 90); end if;
  return 0;
end $function$;


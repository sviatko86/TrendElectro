create or replace function public.assign_products(p_ids text[], p_path text[])
 returns integer language plpgsql security definer set search_path to 'public' as $function$
declare n int;
begin
  if not public.is_admin() then raise exception 'forbidden'; end if;
  if p_path is null or array_length(p_path, 1) is null or array_length(p_path, 1) > 3 then
    raise exception 'Невірний шлях категорії';
  end if;
  update public.products set category = p_path[1], subcategory = p_path[2], subcategory2 = p_path[3], updated_at = now()
  where id = any(p_ids);
  get diagnostics n = row_count;
  return n;
end $function$;

